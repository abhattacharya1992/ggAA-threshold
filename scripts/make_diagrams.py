#!/usr/bin/env python3
"""Figure 1: the Type II tree diagram and the one-loop diagram with the DPS singularity (TikZ-Feynman).

One source serves two routes.  manuscript/figures/fig0_diagrams_tikz.tex holds the tikzpicture; the
manuscript inputs it directly when tikz-feynman.sty is installed, so that the labels are set in the
fonts of the paper (see manuscript/diagram_setup.tex).  The same file is compiled here, inside a
standalone wrapper, to manuscript/figures/fig0_diagrams.pdf, which the manuscript uses otherwise.
Vertices are placed by hand, so pdflatex suffices (no LuaLaTeX).  Panel (b) is labelled with the loop
momentum k; the double parton scattering singularity lies at k = x p1, p3 - k = (1-x) p2.
"""

import pathlib
import shutil
import subprocess
import sys
import tempfile

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "src" / "python"))

from ggaa.paths import FIGURES

TIKZ = r"""% Generated by scripts/make_diagrams.py; do not edit by hand.
{\small
\begin{tikzpicture}
  % (a) Type II tree diagram, t channel
  \begin{feynman}
    \vertex (g1) at (0.9, 2.2) {\(g(p_1)\)};
    \vertex (g2) at (0.9, 0.0) {\(g(p_2)\)};
    \vertex[crossed dot] (v1) at (3.2, 2.2) {};
    \vertex[crossed dot] (v2) at (3.2, 0.0) {};
    \vertex (a3) at (5.5, 2.2) {\(A(p_3)\)};
    \vertex (a4) at (5.5, 0.0) {\(A(p_4)\)};
    \diagram* {
      (g1) -- [gluon] (v1) -- [scalar] (a3),
      (g2) -- [gluon] (v2) -- [scalar] (a4),
      (v1) -- [gluon] (v2),
    };
  \end{feynman}
  \node[anchor=north west] at (-0.3, 2.75) {(a)};

  % (b) one-loop Type II diagram (crossed box); loop momentum k
  \begin{scope}[xshift=6.3cm]
  \begin{feynman}
    \vertex (h1) at (0.9, 2.2) {\(g(p_1)\)};
    \vertex (h2) at (0.9, 0.0) {\(g(p_2)\)};
    \vertex (s1) at (2.0, 2.2);
    \vertex (s2) at (2.0, 0.0);
    \vertex[crossed dot] (e1) at (4.4, 2.2) {};
    \vertex[crossed dot] (e2) at (4.4, 0.0) {};
    \vertex (b1) at (5.7, 2.2) {\(A(p_3)\)};
    \vertex (b2) at (5.7, 0.0) {\(A(p_4)\)};
    \diagram* {
      (h1) -- [gluon] (s1) -- [gluon] (e1) -- [scalar] (b1),
      (h2) -- [gluon] (s2) -- [gluon] (e2) -- [scalar] (b2),
      (s1) -- [gluon] (e2),
      (s2) -- [gluon] (e1),
    };
    % momentum labels placed clear of the gluon coils
    \node at (3.2, 2.62) {\(k\)};
    \node at (3.2, -0.44) {\(p_4-p_1+k\)};
    \node[anchor=east] at (2.45, 1.55) {\(p_1-k\)};
    \node[anchor=west] at (3.95, 1.55) {\(p_3-k\)};
  \end{feynman}
  \node[anchor=north west] at (-0.3, 2.75) {(b)};
  \end{scope}
\end{tikzpicture}}
"""

WRAPPER = r"""\documentclass[border=1pt]{standalone}
\IfFileExists{newtxmath.sty}{\usepackage{newtxtext,newtxmath}}{\usepackage{mathptmx}}
\usepackage[compat=1.1.0]{tikz-feynman}
\tikzfeynmanset{warn luatex=false}
\begin{document}
\input{fig0_diagrams_tikz.tex}
\end{document}
"""


def main():
    FIGURES.mkdir(parents=True, exist_ok=True)
    (FIGURES / "fig0_diagrams_tikz.tex").write_text(TIKZ)
    for old in ("fig0_diagrams.tex",):
        if (FIGURES / old).exists():
            (FIGURES / old).unlink()
    with tempfile.TemporaryDirectory() as tmp:
        shutil.copy(FIGURES / "fig0_diagrams_tikz.tex", tmp)
        (pathlib.Path(tmp) / "fig0_diagrams.tex").write_text(WRAPPER)
        run = subprocess.run(["pdflatex", "-interaction=nonstopmode", "-halt-on-error", "fig0_diagrams.tex"],
                             cwd=tmp, capture_output=True, text=True)
        if run.returncode != 0:
            sys.exit(run.stdout[-2000:])
        shutil.copy(pathlib.Path(tmp) / "fig0_diagrams.pdf", FIGURES / "fig0_diagrams.pdf")
    print("wrote manuscript/figures/fig0_diagrams_tikz.tex and the fallback fig0_diagrams.pdf")


if __name__ == "__main__":
    main()
