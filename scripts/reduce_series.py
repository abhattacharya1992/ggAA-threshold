#!/usr/bin/env python3
"""Reduce the constructed coefficients and write the final series.

For every flavour coefficient M_i,k the construction left one file per power of
beta, data/construction/M{i}_nf{k}_beta_{n}.wl, with n from -4 to 6.  This script

  1. replaces the endpoint constants by their reductions,
  2. checks that every inverse and every odd power vanishes identically,
  3. writes data/series/M{i}_nf{k}.m with the coefficients of beta^0, 2, 4, 6,
     divided by 64 to bring them to the normalization of the tree and one-loop
     amplitudes (ggaa.normalization).
"""

import pathlib
import sys
import time

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "src" / "python"))

import sympy as sp

from ggaa import wolfram
from ggaa.normalization import FILE_FACTOR
from ggaa.paths import CONSTRUCTION, SERIES

HEADER = """(* M_{i}^{{II,(2),fin}}, coefficient of n_f^{k}.
   Threshold expansion {{c0, c2, c4, c6}} with M = c0 + beta^2 c2 + beta^4 c4 + beta^6 c6 + O(beta^8).
   Variables: beta = beta_A, costh = cos(theta), m2 = m_A^2, mu2 = mu_R^2, nc = N_c.
   Normalization: amplitude = C_G^2 [M^(0) + a_s M^(1) + a_s^2 M^(2)] delta^ab, as for the tree
   and one-loop amplitudes of arXiv:1909.08993; equal to the expansion of the published
   two-loop files divided by 64.
   Generated by scripts/reduce_series.py from data/construction. *)
"""


def power(path):
    tag = path.stem.rsplit("_beta_", 1)[1]
    return -int(tag[1:]) if tag.startswith("m") else int(tag)


def main():
    SERIES.mkdir(parents=True, exist_ok=True)
    failures = []
    for i in (1, 2):
        for k in (0, 1, 2):
            files = sorted(CONSTRUCTION.glob(f"M{i}_nf{k}_beta_*.wl"), key=power)
            coefficients = {}
            for path in files:
                start = time.time()
                n = power(path)
                reduced = wolfram.reduce(wolfram.read(path))
                vanishes = wolfram.is_zero(reduced)
                if n < 0 or n % 2:
                    status = "vanishes identically" if vanishes else "DOES NOT VANISH"
                    if not vanishes:
                        failures.append(path.name)
                else:
                    coefficients[n] = sp.expand(reduced / FILE_FACTOR)
                    status = f"{len(wolfram.collect(reduced))} terms"
                print(f"M{i} nf^{k} beta^{n:>2}: {status:22s} ({time.time() - start:.1f} s)", flush=True)
            body = ",\n\n".join(wolfram.to_wolfram(coefficients.get(n, 0)) for n in (0, 2, 4, 6))
            target = SERIES / f"M{i}_nf{k}.m"
            target.write_text(HEADER.format(i=i, k=k) + "{\n" + body + "\n}\n")
            print(f"wrote {target.relative_to(SERIES.parents[1])}")
    if failures:
        sys.exit("non-vanishing inverse or odd powers: " + ", ".join(failures))
    print("All inverse and odd powers vanish identically.")


if __name__ == "__main__":
    main()
